// tsgen は、アイランドに JSON で渡す Go の型と、server と client で揃えるコード値から TS の型を書き出す
package main

import (
	"flag"
	"fmt"
	"os"
	"reflect"
	"slices"
	"strings"

	"github.com/kakkky/gorviz/internal/app/server/domain"
	"github.com/kakkky/gorviz/internal/app/server/presentation/view/components"
	"github.com/kakkky/gorviz/internal/domain/observation"
)

type enum struct {
	name   string
	array  string
	goType reflect.Type
	values []string
}

func values[T ~string](vs []T) []string {
	out := make([]string, 0, len(vs))
	for _, v := range vs {
		out = append(out, string(v))
	}
	return out
}

var enums = []enum{
	{name: "MainCause", array: "MAIN_CAUSES", goType: reflect.TypeFor[domain.MainCause](), values: values(domain.MainCauses)},
	{name: "PlaceKind", array: "PLACE_KINDS", goType: reflect.TypeFor[observation.PlaceKind](), values: values(components.ReplayPlaceKinds)},
	{name: "Certainty", array: "CERTAINTIES", goType: reflect.TypeFor[domain.Certainty](), values: values([]domain.Certainty{domain.CertaintyFact, domain.CertaintyInference})},
}

var roots = []reflect.Type{
	reflect.TypeFor[components.GMPReplayProps](),
	reflect.TypeFor[components.ReplayWindow](),
}

type generator struct {
	b    strings.Builder
	done map[reflect.Type]bool
	todo []reflect.Type
}

func (g *generator) tsType(t reflect.Type) string {
	for _, e := range enums {
		if t == e.goType && e.goType.Kind() == reflect.String {
			return e.name
		}
	}
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64, reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice, reflect.Array:
		return g.tsType(t.Elem()) + "[]"
	case reflect.Map:
		return "Record<string, " + g.tsType(t.Elem()) + ">"
	case reflect.Pointer:
		return g.tsType(t.Elem()) + " | null"
	case reflect.Struct:
		if !g.done[t] && !slices.Contains(g.todo, t) {
			g.todo = append(g.todo, t)
		}
		return t.Name()
	}
	panic("tsgen: unsupported type " + t.String())
}

func (g *generator) iface(t reflect.Type) {
	g.done[t] = true
	fmt.Fprintf(&g.b, "\nexport interface %s {\n", t.Name())
	for f := range t.Fields() {
		if !f.IsExported() {
			continue
		}
		name, opts, _ := strings.Cut(f.Tag.Get("json"), ",")
		if name == "-" {
			continue
		}
		if name == "" {
			name = f.Name
		}
		optional := ""
		if strings.Contains(opts, "omitempty") {
			optional = "?"
		}
		fmt.Fprintf(&g.b, "  %s%s: %s\n", name, optional, g.tsType(f.Type))
	}
	g.b.WriteString("}\n")
}

func main() {
	out := flag.String("out", "src/gen/types.ts", "the file to write")
	flag.Parse()
	g := &generator{done: map[reflect.Type]bool{}}
	g.b.WriteString("// Code generated by go run ./tsgen. DO NOT EDIT.\n")
	for _, e := range enums {
		quoted := make([]string, 0, len(e.values))
		for _, v := range e.values {
			quoted = append(quoted, fmt.Sprintf("%q", v))
		}
		fmt.Fprintf(&g.b, "\nexport const %s = [%s] as const\nexport type %s = (typeof %s)[number]\n", e.array, strings.Join(quoted, ", "), e.name, e.array)
	}
	g.todo = append(g.todo, roots...)
	for len(g.todo) > 0 {
		t := g.todo[0]
		g.todo = g.todo[1:]
		if !g.done[t] {
			g.iface(t)
		}
	}
	if err := os.WriteFile(*out, []byte(g.b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
